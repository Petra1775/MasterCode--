-- Run this once in Supabase SQL Editor. Authentication is provided by Supabase Auth.
create table if not exists public.game_progress (
  user_id uuid primary key references auth.users(id) on delete cascade,
  progress jsonb not null default '{"coins":0,"xp":0,"level":1,"completed":[],"inventory":[]}'::jsonb,
  updated_at timestamptz not null default now()
);

alter table public.game_progress enable row level security;
drop policy if exists "Players can read their own progress" on public.game_progress;
drop policy if exists "Players can create their own progress" on public.game_progress;
drop policy if exists "Players can update their own progress" on public.game_progress;
create policy "Players can read their own progress" on public.game_progress
  for select to authenticated using (auth.uid() = user_id);
create policy "Players can create their own progress" on public.game_progress
  for insert to authenticated with check (auth.uid() = user_id);
create policy "Players can update their own progress" on public.game_progress
  for update to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);

create table if not exists public.quiz_attempts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  level integer not null check (level between 1 and 3),
  score integer not null,
  total integer not null,
  created_at timestamptz not null default now()
);
alter table public.quiz_attempts enable row level security;
drop policy if exists "Players can view their own quiz attempts" on public.quiz_attempts;
drop policy if exists "Players can submit their own quiz attempts" on public.quiz_attempts;
create policy "Players can view their own quiz attempts" on public.quiz_attempts
  for select to authenticated using (auth.uid() = user_id);
create policy "Players can submit their own quiz attempts" on public.quiz_attempts
  for insert to authenticated with check (auth.uid() = user_id);
